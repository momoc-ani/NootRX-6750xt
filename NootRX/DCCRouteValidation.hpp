// Validates the 25E253 align-manager entry and all three identity getter calls.
inline bool validateAlignManagerInit(const uint8_t *function, size_t available) {
    return Detail::matchesAt(function, available, 0, Detail::AlignManagerPrologue) &&
           Detail::matchesAt(function, available, 0xC6, Detail::AlignManagerIdentityGetters);
}

// Validates the 25E253 scanout-DCC decision entry before a wrapper is installed.
inline bool validateShouldAllocScanoutDcc(const uint8_t *function, size_t available) {
    return Detail::matchesAt(function, available, 0, Detail::ScanoutDecisionPrologue);
}

// Validates the 25E253 AddrLib DCC computation entry before a wrapper is installed.
inline bool validateGetDccInfo2(const uint8_t *function, size_t available) {
    return Detail::matchesAt(function, available, 0, Detail::GetDccInfoPrologue);
}

// Validates the 25E253 Framebuffer dispatcher, request 0x1A branch, and jump-table mapping.
inline bool validateFramebufferRequest(const uint8_t *function, size_t available) {
    return Detail::matchesAt(function, available, 0, Detail::FramebufferRequestPrologue) &&
           Detail::matchesAt(function, available, 0x13E, Detail::FramebufferDccRequestBranch) &&
           Detail::matchesAt(function, available, 0x5EA, Detail::FramebufferDccJumpTableEntry);
}

