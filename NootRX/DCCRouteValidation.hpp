// Compares one exact 25E253 instruction sequence after proving the requested range is available.
template<size_t N>
inline bool matchesAt(const uint8_t *function, size_t available, size_t offset, const uint8_t (&expected)[N]) {
    return function != nullptr && offset <= available && N <= available - offset &&
           memcmp(function + offset, expected, N) == 0;
}

